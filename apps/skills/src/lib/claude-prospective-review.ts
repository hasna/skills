export const CLAUDE_PROSPECTIVE_REVIEW_SCHEMA = "skills.claude-plugin-prospective-review/v1" as const;
const SHA256 = /^[a-f0-9]{64}$/;
const MAX_CANDIDATE_FILES = 16_384;
const MAX_CANDIDATE_BYTES = 256 * 1024 * 1024;
const sha = (data: string | Buffer) => createHash("sha256").update(data).digest("hex");
function refuse(reason: string): never { throw new Error(`CLAUDE_CANDIDATE_REVIEW_REFUSED: ${reason}`); }
const GENERATED_MARKETPLACE_TIME = Object.freeze({ $generated: "claude-utc-timestamp", field: "known-marketplaces.lastUpdated" });
const GENERATED_FRESH_PLUGIN_INSTALLED_AT = Object.freeze({ $generated: "claude-utc-timestamp", field: "installed_plugins.fresh-row.installedAt" });
const GENERATED_PLUGIN_UPDATE_TIME = Object.freeze({ $generated: "claude-utc-timestamp", field: "installed_plugins.selected-row.lastUpdated" });
function preserveOrGenerateTimestamp(previous: string, field: string): Record<string, unknown> {
  return { $allowed: [previous, { $generated: "claude-utc-timestamp", field }] };
}

export interface ClaudeProspectiveReviewRequest {
  schema: typeof CLAUDE_PROSPECTIVE_REVIEW_SCHEMA;
  scope: { kind: "user" | "project"; projectPath: string };
  native: { home: string; executable: { path: string; target: string; version: string; sha256: string }; configRoot: string; pluginRoot: string };
  skills: { dataDir: string; policySha256: string; discoverySha256: string; discoveryInputs: ReviewedDiscoveryInputs };
  candidate: { marketplace: string; root: string; catalogPath: string; catalogSha256: string; closureSha256: string; plugins: Array<{ plugin: string; manifestPath: string; manifestSha256: string; optionsPatch: Record<string, unknown> }>; releaseManifest?: { path: string; sha256: string }; functionHooksEnv?: "1" };
  preimages: {
    settings: { path: string; sha256: string | null };
    userSettings: { path: string; sha256: string | null };
    projectSettings: { path: string; sha256: string | null };
    projectSettingsLocal: { path: string; sha256: string | null };
    marketplaces: { path: string; sha256: string | null };
    installedPlugins: { path: string; sha256: string | null };
  };
  /** Complete semantic documents expected after native adoption. The one
   * timestamps generated by Claude for the owned marketplace and registration
   * rows use exact typed field markers documented below; every other field is
   * concrete. */
  delta: {
    settingsAfter: Record<string, unknown>;
    knownMarketplacesAfter: Record<string, unknown>;
    installedPluginsAfter: Record<string, unknown>;
  };
  review: { pluginHooks: "reviewed-no-skill-injection" };
}

