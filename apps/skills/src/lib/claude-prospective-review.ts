/** Read-only admission check for a prospective Claude plugin installation.
 * This validates a frozen candidate and the current Skills/native preimages;
 * it does not call Claude, write settings, install a marketplace, or claim that
 * Claude's installer is atomic or recoverable after a crash.
 */
