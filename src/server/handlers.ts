import { createHash } from "node:crypto";
import { ArtifactStorage } from "./artifact-storage.js";
import { createArtifactId } from "./store.js";
import { redactForClient } from "./redaction.js";
import type { ServerArtifact, ServerRunRecord, SkillsProductStore } from "./types.js";

const DETERMINISTIC_TEXT_HANDLERS = new Set([
  "audio-transcript-pack",
  "transcript",
  "video-highlight-pack",
]);

export async function executeRun(store: SkillsProductStore, run: ServerRunRecord, storage = new ArtifactStorage()): Promise<ServerRunRecord> {
  try {
    await store.appendLog(run.id, run.orgId, "info", redactForClient(`starting run ${run.skill}`));
    if (!DETERMINISTIC_TEXT_HANDLERS.has(run.skill)) {
      await store.appendLog(run.id, run.orgId, "warn", `${run.skill} has no provider-free handler yet`);
      return await failRun(store, run, "HANDLER_UNAVAILABLE", "This deployment has no safe provider-free handler for that skill yet.");
    }

    const text = extractText(run);
    if (!text.trim()) {
      return await failRun(store, run, "INVALID_INPUT", "Provide transcript text with input.transcript, input.text, --text, --source, or positional text.");
    }

    const title = extractOption(run.args, "--title") || stringInput(run.input, "title") || "Skills run";
    const summary = summarize(text);
    const artifacts = [
      textArtifact(run, "transcript.md", `# ${title}\n\n${text.trim()}\n`),
      textArtifact(run, "summary.md", `# Summary\n\n${summary}\n`),
      textArtifact(run, "show-notes.md", `# Show Notes\n\n- ${summary}\n- Generated by the open-skills deterministic worker.\n`),
      textArtifact(run, "clips.csv", `start,end,title,summary\n00:00,00:30,\"Opening\",\"${csv(summary)}\"\n`),
      textArtifact(run, "manifest.json", JSON.stringify({
        runId: run.id,
        skill: run.skill,
        requestedSlug: run.requestedSlug,
        generatedAt: new Date().toISOString(),
        artifacts: ["transcript.md", "summary.md", "show-notes.md", "clips.csv"],
      }, null, 2) + "\n", "application/json"),
    ];

    for (const artifact of artifacts) {
      await store.addArtifact(await storage.materialize(run, artifact.meta, artifact.body));
    }
    await store.appendLog(run.id, run.orgId, "info", `generated ${artifacts.length} artifacts`);
    return await completeRun(store, run, summary);
  } catch (error) {
    return await failRun(store, run, "WORKER_ERROR", redactForClient((error as Error).message));
  }
}

function textArtifact(
  run: ServerRunRecord,
  relativePath: string,
  bodyText: string,
  contentType = relativePath.endsWith(".json") ? "application/json" : "text/markdown; charset=utf-8",
): {
  meta: Omit<ServerArtifact, "createdAt" | "storageKind" | "storageKey" | "bodyText">;
  body: { relativePath: string; bodyText: string; contentType: string };
} {
  const bytes = new TextEncoder().encode(bodyText);
  return {
    meta: {
      id: createArtifactId(),
      runId: run.id,
      orgId: run.orgId,
      fileName: relativePath.split("/").pop() || relativePath,
      relativePath,
      contentType,
      byteSize: bytes.byteLength,
      sha256: createHash("sha256").update(bytes).digest("hex"),
    },
    body: { relativePath, bodyText, contentType },
  };
}

async function completeRun(store: SkillsProductStore, run: ServerRunRecord, preview: string): Promise<ServerRunRecord> {
  const next = await store.updateRun(run.id, {
    status: "succeeded",
    outputType: "artifact_bundle",
    outputPreview: preview,
    completedAt: new Date().toISOString(),
  });
  return next ?? run;
}

async function failRun(
  store: SkillsProductStore,
  run: ServerRunRecord,
  code: string,
  message: string,
): Promise<ServerRunRecord> {
  await store.appendLog(run.id, run.orgId, "error", message);
  const next = await store.updateRun(run.id, {
    status: "failed",
    errorCode: code,
    errorMessage: message,
    completedAt: new Date().toISOString(),
  });
  return next ?? run;
}

function extractText(run: ServerRunRecord): string {
  return stringInput(run.input, "transcript")
    || stringInput(run.input, "text")
    || extractOption(run.args, "--text")
    || extractOption(run.args, "--source")
    || run.args.filter((arg) => !arg.startsWith("--")).join(" ");
}

function stringInput(input: Record<string, unknown>, key: string): string | undefined {
  const value = input[key];
  return typeof value === "string" && value.trim() ? value : undefined;
}

function extractOption(args: string[], flag: string): string | undefined {
  for (let i = 0; i < args.length; i++) {
    const arg = args[i];
    if (arg === flag && args[i + 1]) return args[i + 1];
    if (arg.startsWith(`${flag}=`)) return arg.slice(flag.length + 1);
  }
  return undefined;
}

function summarize(text: string): string {
  const normalized = redactForClient(text).replace(/\s+/g, " ").trim();
  if (normalized.length <= 220) return normalized;
  return `${normalized.slice(0, 217)}...`;
}

function csv(value: string): string {
  return value.replace(/"/g, '""');
}
